-- =============================================================================
-- 数据库初始化 —— 只在数据卷为空时执行一次（postgres 容器首次启动）
-- =============================================================================
-- 这里只做 Flyway 做不了或不该做的事：
--   1. 安装扩展（需要超级用户）
--   2. 建 schema 与角色（权限边界，属基础设施而非业务迁移）
--
-- 业务表结构全部由 Flyway 管理（backend/src/main/resources/db/migration/），
-- 不在本文件里建表——否则会出现两个真相源。
-- =============================================================================

-- pgvector：向量检索的基础。必须在任何 VECTOR 列之前存在。
CREATE EXTENSION IF NOT EXISTS vector;

-- 用于法条全文检索（PRD 3.5.3 的混合检索里词法那一路）
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS unaccent;

-- =============================================================================
-- Schema 边界
-- =============================================================================
-- 依据 docs/detailed-design.md 的裁决（4+1 的 AD-4 与 PRD 3.3 原本互相矛盾）：
--
--   kb.*  —— 法规 / 法条 / 本体 / wiki / 向量 / 入库任务
--            由 Python `ai` 服务**独占写**，`api` 只读
--   app.* —— 租户 / 用户 / 会话 / 审计 / 发布记录
--            由 Java `api` 服务**独占写**，`ai` 只读
--
-- 这条边界同时决定了 Flyway 归属与数据库授权，必须在建表之前定死。
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS kb;
CREATE SCHEMA IF NOT EXISTS app;
CREATE SCHEMA IF NOT EXISTS runtime;

COMMENT ON SCHEMA kb      IS '知识层：由 ai 服务独占写，api 只读';
COMMENT ON SCHEMA app     IS '应用层：由 api 服务独占写，ai 只读';
COMMENT ON SCHEMA runtime IS
    'ai 服务的运行态：LangGraph 检查点表等框架自建对象。'
    '单独成 schema 的理由有二：① 检查点既不是知识(kb)也不是应用数据(app)，'
    '混进去会模糊既有的写权限边界；② public 被刻意收紧了建表权限'
    '（见文件末尾的 REVOKE），框架的 setup() 需要一块可写的落脚地。';

-- =============================================================================
-- 应用角色
-- =============================================================================
-- 关键点：**应用角色不是表的 owner**。
--
-- 因为 PostgreSQL 的行级安全策略（RLS）默认对表 owner 不生效——如果应用角色
-- 同时是 owner，RLS 就形同虚设，多租户隔离会静默失效。这正是 R3 风险的核心。
--
-- 做法：表由迁移角色（POSTGRES_USER，即 superuser）创建，应用角色只被授权。
-- 迁移文件里仍会显式写 FORCE ROW LEVEL SECURITY 作为第二道保险。

-- 注意：应用角色**不在这里创建，也不在这里授权**。
-- 它的口令必须来自环境变量 DB_PASSWORD，而纯 SQL 文件读不到环境变量，
-- 只能硬编码——硬编码的口令会与 .env 里的随机值不一致，导致应用连不上库。
-- 因此角色创建与授权都放在 02-app-role.sh 里，由 shell 读取环境变量后执行。

-- 禁止 public schema 被随意创建对象（PG15+ 已默认收紧，此处显式声明）
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
