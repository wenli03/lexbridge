"""红线规则集合：把「不协助什么」写成可维护的数据。

**这个模块不导入 `app.chains`**（DR-4，由 import-linter 在 CI 强制）。
理由不是洁癖：如果红线判定调用模型，就存在"把模型说服之后绕过红线"的路径，
而这条路径的失败方式是静默的——用户拿到了一份本该被拒绝的方案。

规则的写法有两条纪律：

1. **匹配"违法意图"，而不是匹配"税务话题"。** `税务筹划`、`法域差异`、
   `控股架构` 这些词本身完全合法，把它们当特征会把正当业务全拦下来，
   而只测召回率的系统最终一定会退化成"一律拒答"。因此触发词一律是
   **隐瞒、伪造、虚假、不申报、无实质**这类指向违法性的动词。
2. **区分"询问后果"与"索取方案"。** 「税法对隐匿收入如何处罚」是合规问题，
   「帮我把收入隐匿掉」才是越界请求。这一层由 `engine.py` 的问询语境判断处理。
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class RedlineRule:
    """一条红线规则。"""

    rule_id: str
    category: str
    #: 触发模式。命中任一条即进入候选，最终是否拒答由 engine 结合语境决定。
    cues: tuple[re.Pattern[str], ...]
    #: 面向用户的判定依据（拒答响应五要素之一）。
    rationale: str
    #: 合法替代路径（拒答响应五要素之一，必须 ≥1 条）。
    legal_alternatives: tuple[str, ...]

    def matched_sentences(self, sentences: list[str]) -> list[str]:
        return [s for s in sentences if any(cue.search(s) for cue in self.cues)]


def _compile(*patterns: str) -> tuple[re.Pattern[str], ...]:
    return tuple(re.compile(pattern) for pattern in patterns)


