import { ApiError } from './client'

/**
 * 判断一次请求失败是否等于「服务端根本没有这个接口」。
 *
 * ## 为什么需要这个判断，而不是直接写死"此功能未实现"
 *
 * 本项目的交付是分阶段的：前端页面已经建好，而咨询链路与入库流水线的服务端
 * 尚未实现。若不做处理，这些页面会显示一个红色的「加载失败」——
 * 它把"这一块还没做"表达成了"这一块坏了"，两者对看代码的人是不同的结论。
 *
 * 但**也不能把页面直接写死成占位**：那样等后端实现之后，页面不会自动变好，
 * 还会留下一段需要记得删掉的代码。
 *
 * 折中是**由真实观察驱动**：照常发请求，只有服务端确实回 404（没有这个路由）
 * 时才换成诚实的说明面板；一旦接口存在，页面立刻正常工作，无需改代码。
 *
 * ## 为什么认 404 而不是认某个错误码
 *
 * 路由不存在时，响应由 Spring 的 `NoHandlerFoundException` 分支或 Boot 的默认
 * 错误页产出，两者的 `code` 字段并不相同（前者是 `NOT_FOUND`，后者是
 * `INTERNAL_ERROR` 一类的通用码），但 HTTP 状态码都是 404。
 * 认状态码比认 code 稳。
 *
 * ## 一个已知的歧义
 *
 * 后端**刻意**把跨租户访问也伪装成 404（见 `GlobalExceptionHandler`：
 * 区分"无权限"与"不存在"等于对外提供了一个资源枚举接口）。
 * 因此一个 404 严格来说有两种可能。对本文件的使用场景——集合型接口
 * （`/consult-sessions`、`/knowledge/review`）——不存在跨租户语义，
 * 所以不构成误判；但**不要**把这个判断用到按 id 取资源的接口上。
 */
export function isEndpointMissing(error: unknown): boolean {
  return error instanceof ApiError && error.status === 404
}
